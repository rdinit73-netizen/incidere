// Add Italian accented characters using base glyphs + diacritic strokes
const ACCENTED_MAP: Record<string, { base: string; accent: 'grave' | 'acute' }> = {
  à: { base: 'a', accent: 'grave' },
  è: { base: 'e', accent: 'grave' },
  é: { base: 'e', accent: 'acute' },
  ì: { base: 'i', accent: 'grave' },
  ò: { base: 'o', accent: 'grave' },
  ù: { base: 'u', accent: 'grave' },
  À: { base: 'A', accent: 'grave' },
  È: { base: 'E', accent: 'grave' },
  É: { base: 'E', accent: 'acute' },
  Ì: { base: 'I', accent: 'grave' },
  Ò: { base: 'O', accent: 'grave' },
  Ù: { base: 'U', accent: 'grave' },
};

function getGlyph(char: string): GlyphDef {
  if (GLYPHS[char]) return GLYPHS[char];
  const acc = ACCENTED_MAP[char];
  if (acc) {
    const base = GLYPHS[acc.base] || GLYPHS[' '];
    const cx = base.width / 2;
    const isUpper = acc.base === acc.base.toUpperCase();
    const yTop = isUpper ? -1.4 : 1.4;
    const yBot = isUpper ? 0.1 : 2.9;
    const accentStroke =
      acc.accent === 'grave'
        ? [[cx - 1.1, yTop], [cx + 0.7, yBot]]
        : [[cx + 1.1, yTop], [cx - 0.7, yBot]];
    return {
      width: base.width,
      strokes: [...base.strokes, accentStroke],
    };
  }
  return GLYPHS[' '];
}

export function layoutVectorText(
  text: string,
  centerX: number,
  centerY: number,
  fontSizeMm: number,
  letterSpacingMultiplier = 1.0,
  lineSpacingMultiplier = 1.45,
  boldDouble = false
): Point2D[][] {
  const lines = text.split('\n');
  const scale = fontSizeMm / 10; // cap height ~10 units (y=1..11)
  const lineHeight = fontSizeMm * lineSpacingMultiplier;
  const totalHeight = (lines.length - 1) * lineHeight + fontSizeMm;
  const startTopY = centerY - totalHeight / 2;

  const result: Point2D[][] = [];

  lines.forEach((line, lineIdx) => {
    const glyphs = Array.from(line).map((ch) => getGlyph(ch));
    const totalLineWidth = glyphs.reduce(
      (sum, g, i) => sum + g.width * scale * (i < glyphs.length - 1 ? letterSpacingMultiplier : 1),
      0
    );

    let cursorX = centerX - totalLineWidth / 2;
    // y=1 is top of cap, y=11 is baseline -> shift so top of cap aligns nicely
    const lineTopY = startTopY + lineIdx * lineHeight - 1 * scale;

    glyphs.forEach((g) => {
      for (const stroke of g.strokes) {
        const pts: Point2D[] = stroke.map(([gx, gy]) => ({
          x: cursorX + gx * scale,
          y: lineTopY + gy * scale,
        }));
        result.push(pts);

        if (boldDouble) {
          const offset = Math.max(0.22, fontSizeMm * 0.025);
          result.push(
            pts.map((p) => ({
              x: p.x + offset,
              y: p.y + offset * 0.4,
            }))
          );
        }
      }
      cursorX += g.width * scale * letterSpacingMultiplier;
    });
  });

  return result;
}
